-- 「默认写封面」的出厂值从 true 改成 false（一次性）。
--
-- 背景：封面是「替换」写而不是追加，而这个键的出厂默认一直是 true —— 于是写入面板里
-- 「写封面」一直是预勾选的，用户在没注意的情况下就会把旧封面换掉（实机报障：
-- 「封面没勾写入也自动覆盖了」）。默认应当是不动用户没要求动的东西。
--
-- 只针对「还停在出厂值 true」的行。迁移只跑一次，之后你在设置页里明确打开
-- 「默认写封面」会照常生效（新写入面板会跟着变成预勾选）。
UPDATE settings
   SET value = 'false'::jsonb
 WHERE key = 'write_cover'
   AND value = 'true'::jsonb;
